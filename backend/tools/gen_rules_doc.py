"""Generate docs/RULES.md from the scenario data so the documentation cannot drift from the rules.

Run from backend/:  .venv\\Scripts\\python tools\\gen_rules_doc.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from app.engine.engine import LABELS  # noqa: E402
from app.scenario.events import EVENTS  # noqa: E402
from app.scenario.rounds import ROUNDS  # noqa: E402


def cond(c):
    if c.op in ("has", "lacks"):
        return f"flag `{c.value}` {c.op}"
    return f"`{c.key} {c.op} {c.value}`"


def fx_line(fx):
    parts = [f"{LABELS.get(k, k)} {v:+g}" for k, v in fx.add.items()]
    parts += [f"{LABELS.get(k, k)} := {v}" for k, v in fx.set.items()]
    parts += [f"+flag `{f}`" for f in fx.on] + [f"-flag `{f}`" for f in fx.off]
    when = f" _when {' and '.join(cond(c) for c in fx.when)}_" if fx.when else ""
    return "; ".join(parts) + when


out = [
    "# BLACKOUT rules reference\n",
    "_Generated by `backend/tools/gen_rules_doc.py` from the scenario data. Do not edit by hand._\n",
    "Budget is in lakh rupees. **Time cost** is minutes of dispatch slack (starts at 300; below 0 the "
    "6:00 AM dispatch is missed). Effects of one action are evaluated against the state *before* the action.\n",
    "## Decisions\n",
]
for r in ROUNDS.values():
    out.append(f"### Round {r.number} — {r.clock}: {r.title}\n")
    for c in r.choices:
        out.append(f"**`{c.id}`** — {c.label}  \nCost ₹{c.cost:g} lakh · time {c.time_cost} min"
                   + (" · needs confirmation" if c.confirm else ""))
        for c2, why in c.requires:
            out.append(f"- Requires {cond(c2)} ({why})")
        for fx in c.effects:
            out.append(f"- {fx_line(fx)}")
        out.append("")
out.append("## Events\n")
out.append("Fire on entering a round in their window when conditions hold and a seeded roll "
           "(`sha256(seed:event:round)`) is below the probability. Each fires at most once.\n")
for e in sorted(EVENTS, key=lambda e: (e.first_round, e.id)):
    cs = " and ".join(cond(c) for c in e.conditions) or "always"
    out.append(f"**`{e.id}`** — {e.title} · rounds {e.first_round}–{e.last_round} · p={e.probability:g} · {cs}")
    for fx in e.effects:
        out.append(f"- {fx_line(fx)}")
    out.append("")
path = pathlib.Path(__file__).resolve().parents[2] / "docs" / "RULES.md"
path.parent.mkdir(exist_ok=True)
path.write_text("\n".join(out), encoding="utf-8")
print("wrote", path)
